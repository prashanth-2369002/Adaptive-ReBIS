def case69():
    """Return a pandapower net of the IEEE 69-bus feeder (bus index = number - 1)."""
    net = pp.create_empty_network(name="IEEE 69-bus", f_hz=50.0, sn_mva=100.0)
    for i in range(69):
        pp.create_bus(net, vn_kv=12.66, name=str(i + 1), index=i)
    pp.create_ext_grid(net, bus=0, vm_pu=1.0)
    for f, t, r, x, p, q in BRANCHES:
        pp.create_line_from_parameters(
            net, from_bus=f - 1, to_bus=t - 1, length_km=1.0,
            r_ohm_per_km=r, x_ohm_per_km=x, c_nf_per_km=0.0, max_i_ka=99.0)
        if p or q:
            pp.create_load(net, bus=t - 1, p_mw=p / 1000, q_mvar=q / 1000)
    return net
